/**
 * Farbschlüssel der feinen Sprites: '#' Grundfarbe, '+' Glanzlicht, '-' Schatten,
 * 'k' tiefer Schatten, 'o' Weiß, '*' Signallicht, 'c' Glas.
 */
function tones(base: string): Record<string, string> {
  return {
    '#': base,
    '+': C.shade(base, 0.5),
    '-': C.shade(base, -0.45),
    k: C.shade(base, -0.8),
    o: C.WHITE,
    '*': C.YELLOW,
    c: C.CYAN,
  };
}

